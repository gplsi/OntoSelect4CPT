# ── main ──────────────────────────────────────────────────────────────────────
def main():
  if not all(value.strip() for value in (BASEPATH, OUTPUT_FILE, SIMILARITY_JSON)):
      raise ValueError("Set BASEPATH, OUTPUT_FILE, and SIMILARITY_JSON before running.")

  if not os.path.exists(BASEPATH):
      logger.error(f"Directory does not exist: {BASEPATH}")
      return

  logger.info("Searching for TTL files...")
  ttl_files = find_ttl_files(BASEPATH)
  total = len(ttl_files)

  logger.info(f"Found {total} TTL files")

  similarity_map = load_similarity_map(SIMILARITY_JSON)

  from transformers import AutoTokenizer
  logger.info(f"Loading tokenizer: {LLAMA_TOKENIZER_MODEL}")
  llama_tokenizer = AutoTokenizer.from_pretrained(
      LLAMA_TOKENIZER_MODEL, token=os.environ.get("HF_TOKEN"), use_fast=True,
  )

  results: List[dict] = []

  for i, file_info in enumerate(ttl_files, start=1):
      logger.info(f"Processing {i}/{total}: {file_info['relative_path']}")

      try:
          size_mb = get_file_size_mb(file_info['full_path'])
          char_count = get_file_char_count(file_info['full_path'])

          ttl_info = analyze_ttl_file(file_info['full_path'])

          similarity = similarity_map.get(file_info['filename'])

          if similarity is None:
              logger.warning(f"No similarity score found for {file_info['filename']}")

          row = build_row(
              file_info=file_info,
              ttl_info=ttl_info,
              size_mb=size_mb,
              char_count=char_count,
              similarity=similarity,
          )
          try:
              row['NumTokensLlama32_3B'] = count_llama_tokens(
                  llama_tokenizer, file_info['full_path'],
              )
          except Exception as e:
              logger.error(f"Error counting tokens in {file_info['relative_path']}: {e}")
              row['Error'] = '; '.join(filter(None, [row['Error'], f"Tokens Llama: {e}"]))

      except Exception as e:
          logger.error(f"Error processing {file_info['relative_path']}: {e}")
          row = build_error_row(file_info, e)

      results.append(row)

      try:
          save_excel(results, OUTPUT_FILE)
          logger.info(f"  Excel updated ({i}/{total})")
      except Exception as e:
          logger.error(f"  Error saving Excel: {e}")

  df = pd.DataFrame(results)

  print("\n===== FULL ANALYSIS SUMMARY =====")
  print(f"Domains: {df['Dominio'].nunique()}  |  Ontologies: {len(df)}")
