# ── TTL file discovery ──────────────────────────────────────────────────
def find_ttl_files(root_path):
  ttl_files = []
  exclude_normalized = [os.path.normpath(p) for p in EXCLUDE_PATHS]

  print(f"[find_ttl_files] Searching in {root_path}")
  print(f"[find_ttl_files] Excluded paths: {exclude_normalized}")

  for root, dirs, files in os.walk(root_path, followlinks=True):
      root_norm = os.path.normpath(root)

      if any(
          root_norm == excl or root_norm.startswith(excl + os.sep)
          for excl in exclude_normalized
      ):
          print(f"  [EXCLUDED] {root_norm}")
          dirs.clear()
          continue

      dirs.sort()

      ttl_in_this_dir = [f for f in files if f.lower().endswith('.ttl')]

      if ttl_in_this_dir:
          print(f"  [DIR] {root_norm}: {len(ttl_in_this_dir)} .ttl files found")

      for file in ttl_in_this_dir:
          full_path = os.path.join(root, file)
          rel_path = os.path.relpath(full_path, root_path)
          path_parts = rel_path.split(os.sep)
          domain = path_parts[0] if len(path_parts) >= 2 else 'unknown'

          ttl_files.append({
              'domain': domain,
              'ontology': Path(file).stem,
              'filename': file,
              'full_path': full_path,
              'relative_path': rel_path,
          })

  print(f"[find_ttl_files] Total TTL files found: {len(ttl_files)}")
  return ttl_files


