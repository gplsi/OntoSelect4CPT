def count_axioms(g: Graph) -> Tuple[int, int]:
  ANNOTATION_PROPS = {
      RDFS.label, RDFS.comment, SKOS.prefLabel, SKOS.altLabel,
      SKOS.hiddenLabel, SKOS.definition, DC.description, DCTERMS.description,
      SCHEMA.description, IAO["IAO_0000115"],
      OBOINOWL.hasExactSynonym, OBOINOWL.hasRelatedSynonym,
      OBOINOWL.hasBroadSynonym, OBOINOWL.hasNarrowSynonym,
      URIRef("http://purl.org/dc/elements/1.1/title"),
      URIRef("http://purl.org/dc/terms/title"),
      URIRef("http://purl.org/dc/elements/1.1/creator"),
      URIRef("http://purl.org/dc/terms/creator"),
      URIRef("http://www.w3.org/2002/07/owl#versionInfo"),
      URIRef("http://purl.org/dc/elements/1.1/date"),
      URIRef("http://purl.org/dc/terms/date"),
      URIRef("http://www.w3.org/2000/01/rdf-schema#seeAlso"),
      URIRef("http://www.w3.org/2000/01/rdf-schema#isDefinedBy"),
  }

  total_axioms = len(g)
  logical_axioms = sum(1 for _, p, _ in g if p not in ANNOTATION_PROPS)
  return total_axioms, logical_axioms


def count_properties_total(g: Graph) -> int:
  all_props: Set[URIRef] = set()
  for rdf_type in (OWL.ObjectProperty, OWL.DatatypeProperty, OWL.AnnotationProperty):
      for s in g.subjects(RDF.type, rdf_type):
          if isinstance(s, URIRef):
              all_props.add(s)
  return len(all_props)


# ── Schema metrics ───────────────────────────────────────────────────────
def compute_attribute_richness(g: Graph, valid_classes: Set[URIRef], C: int) -> float:
  if C == 0:
      return 0.0

  class_att: Dict[URIRef, Set[URIRef]] = defaultdict(set)
  undomained: Set[URIRef] = set()

  for prop in g.subjects(RDF.type, OWL.DatatypeProperty):
      if not isinstance(prop, URIRef):
          continue

      domains = [
          d for d in g.objects(prop, RDFS.domain)
          if isinstance(d, URIRef) and d in valid_classes
      ]

      if domains:
          for d in domains:
              class_att[d].add(prop)
      else:
          undomained.add(prop)

  total_att = sum(len(v) for v in class_att.values()) + len(undomained)
  return total_att / C


def compute_property_density(g: Graph, valid_classes: Set[URIRef], C: int) -> float:
  """Count distinct properties per class without inheritance or OWL inference.
  Link properties through rdfs:domain or direct predicate use on the class.
  A shared property counts for each linked class; unlinked properties do not count.
  Include known annotation predicates even when they are not explicitly declared."""
  if C == 0:
      return 0.0
  data_props = {p for p in g.subjects(RDF.type, OWL.DatatypeProperty)
                if isinstance(p, URIRef)}
  anno_props = {p for p in g.subjects(RDF.type, OWL.AnnotationProperty)
                if isinstance(p, URIRef)} | set(NAME_PROPS_STRICT) | set(DESC_PROPS)
  total = 0
  for props in (data_props, anno_props):
      linked = defaultdict(set)
      for prop in props:
          for c in g.objects(prop, RDFS.domain):
              if c in valid_classes:
                  linked[c].add(prop)
          for c in g.subjects(prop, None):
              if c in valid_classes:
                  linked[c].add(prop)
      total += sum(len(properties) for properties in linked.values())
  return total / C


def compute_relationship_richness(H: int, P: int) -> float:
  denominator = H + P
  return P / denominator if denominator > 0 else 0.0


def compute_attribute_class_ratio(g: Graph, valid_classes: Set[URIRef], C: int) -> float:
  if C == 0:
      return 0.0

  classes_with_attributes: Set[URIRef] = set()

  for prop in g.subjects(RDF.type, OWL.DatatypeProperty):
      if not isinstance(prop, URIRef):
          continue

      for domain in g.objects(prop, RDFS.domain):
          if isinstance(domain, URIRef) and domain in valid_classes:
              classes_with_attributes.add(domain)

  return len(classes_with_attributes) / C


def compute_equivalence_ratio(g: Graph, valid_classes: Set[URIRef], C: int) -> float:
  if C == 0:
      return 0.0

  equivalent_classes: Set[URIRef] = set()

  for s, _, o in g.triples((None, OWL.equivalentClass, None)):
      if isinstance(s, URIRef) and s in valid_classes:
          equivalent_classes.add(s)
      if isinstance(o, URIRef) and o in valid_classes:
          equivalent_classes.add(o)

  return len(equivalent_classes) / C


def compute_axiom_class_ratio(num_logical_axioms: int, C: int) -> float:
  return num_logical_axioms / C if C > 0 else 0.0


def compute_inverse_relations_ratio(g: Graph) -> float:
  all_obj_props = {
      s for s in g.subjects(RDF.type, OWL.ObjectProperty)
      if isinstance(s, URIRef)
  }

  all_data_props = {
      s for s in g.subjects(RDF.type, OWL.DatatypeProperty)
      if isinstance(s, URIRef)
  }

  props_with_inverse: Set[URIRef] = set()

  for s, _, o in g.triples((None, OWL.inverseOf, None)):
      if isinstance(s, URIRef) and s in all_obj_props:
          props_with_inverse.add(s)
      if isinstance(o, URIRef) and o in all_obj_props:
          props_with_inverse.add(o)

  inv_functional_obj = {
      s for s in g.subjects(RDF.type, OWL.InverseFunctionalProperty)
      if isinstance(s, URIRef) and s in all_obj_props
  }

  IOP = len(props_with_inverse | inv_functional_obj)

  IFDP = len({
      s for s in g.subjects(RDF.type, OWL.InverseFunctionalProperty)
      if isinstance(s, URIRef) and s in all_data_props
  })

  AOP = len(all_obj_props)

  AFDP = len({
      s for s in g.subjects(RDF.type, OWL.FunctionalProperty)
      if isinstance(s, URIRef) and s in all_data_props
  })

  denominator = AOP + AFDP
  return (IOP + IFDP) / denominator if denominator > 0 else 0.0


# ── Knowledge base metrics ──────────────────────────────────────────
def compute_knowledge_base_metrics(
  g: Graph,
  valid_classes: Set[URIRef],
  C: int,
  individuals: Set[URIRef],
) -> Dict[str, float]:
  if C == 0:
      return {
          'AP_average_population': 0.0,
          'CR_class_richness': 0.0,
      }

  AP = len(individuals) / C

  non_empty_classes: Set[URIRef] = set()
  for _, _, o in g.triples((None, RDF.type, None)):
      if isinstance(o, URIRef) and o in valid_classes:
          non_empty_classes.add(o)

  CR = len(non_empty_classes) / C

  return {
      'AP_average_population': float(AP),
      'CR_class_richness': float(CR),
  }


# ── Graph metrics ─────────────────────────────────────────────────────────
def compute_graph_metrics(
  valid_classes: Set[URIRef],
  valid_subclass_edges: List[Tuple[URIRef, URIRef]],
) -> Dict[str, float]:

  C = len(valid_classes)

  if C == 0:
      return {k: 0.0 for k in [
          'abs_root_cardinality', 'abs_leaf_cardinality', 'abs_sibling_cardinality',
          'abs_depth', 'avg_depth', 'max_depth', 'abs_breadth', 'avg_breadth',
          'max_breadth', 'min_breadth', 'ratio_leaf_fanoutness',
          'ratio_sibling_fanoutness', 'tangledness', 'num_multi_parent_classes',
          'TNOP', 'ANOP', 'cycle_detected',
      ]}

  parents_of: Dict[URIRef, Set[URIRef]] = defaultdict(set)
  children_of: Dict[URIRef, Set[URIRef]] = defaultdict(set)

  for child, parent in valid_subclass_edges:
      if parent in valid_classes:
          parents_of[child].add(parent)
          children_of[parent].add(child)

  roots = {c for c in valid_classes if not parents_of.get(c)}
  leaves = {c for c in valid_classes if not children_of.get(c)}

  abs_root_cardinality = len(roots)
  abs_leaf_cardinality = len(leaves)

  total_siblings = 0
  for node in valid_classes:
      siblings: Set[URIRef] = set()
      for p in parents_of.get(node, set()):
          siblings.update(children_of.get(p, set()))
      siblings.discard(node)
      total_siblings += len(siblings)

  abs_sibling_cardinality = total_siblings

  multi_parent_classes = {
      c for c in valid_classes
      if len(parents_of.get(c, set())) > 1
  }

  num_multi_parent = len(multi_parent_classes)
  tangledness = num_multi_parent / C

  visiting: Set[URIRef] = set()
  memo: Dict[URIRef, Tuple[int, int]] = {}
  cycle_detected = False

  def dp_paths(node: URIRef) -> Tuple[int, int]:
      nonlocal cycle_detected

      if node in memo:
          return memo[node]

      if node in visiting:
          cycle_detected = True
          return 0, 0

      visiting.add(node)

      if node in roots:
          result = (1, 0)
      else:
          num_paths, sum_len = 0, 0
          for parent in parents_of.get(node, set()):
              if parent in valid_classes:
                  p_n, p_s = dp_paths(parent)
                  num_paths += p_n
                  sum_len += p_s + p_n
          result = (num_paths, sum_len)

      visiting.discard(node)
      memo[node] = result
      return result

  for node in valid_classes:
      dp_paths(node)

  TNOP = sum(np for np, _ in memo.values())
  ANOP = TNOP / C if C > 0 else 0.0

  abs_depth = sum(memo[leaf][1] for leaf in leaves if leaf in memo)
  total_paths_to_leaves = sum(memo[leaf][0] for leaf in leaves if leaf in memo)
  avg_depth = abs_depth / total_paths_to_leaves if total_paths_to_leaves > 0 else 0.0

  max_depth_val = 0.0

  if not cycle_detected:
      max_memo: Dict[URIRef, int] = {}
      vis2: Set[URIRef] = set()

      def dp_max(node: URIRef) -> int:
          if node in max_memo:
              return max_memo[node]

          if node in vis2:
              return 0

          vis2.add(node)

          if node in roots:
              result = 0
          else:
              result = max(
                  (dp_max(p) + 1 for p in parents_of.get(node, set()) if p in valid_classes),
                  default=0,
              )

          vis2.discard(node)
          max_memo[node] = result
          return result

      for node in valid_classes:
          dp_max(node)

      max_depth_val = float(max(max_memo.values(), default=0))

  level_sizes: List[int] = []

  if roots:
      current_level: Set[URIRef] = set(roots)
      visited_bfs: Set[URIRef] = set(roots)

      while current_level:
          level_sizes.append(len(current_level))
          next_level: Set[URIRef] = set()

          for node in current_level:
              for child in children_of.get(node, set()):
                  if child not in visited_bfs:
                      visited_bfs.add(child)
                      next_level.add(child)

          current_level = next_level

  abs_breadth = sum(level_sizes)
  num_levels = len(level_sizes)
  avg_breadth = abs_breadth / num_levels if num_levels > 0 else 0.0
  max_breadth = float(max(level_sizes, default=0))
  min_breadth = float(min(level_sizes, default=0))

  ratio_leaf_fanoutness = abs_leaf_cardinality / C
  ratio_sibling_fanoutness = abs_sibling_cardinality / C

  return {
      'abs_root_cardinality': float(abs_root_cardinality),
      'abs_leaf_cardinality': float(abs_leaf_cardinality),
      'abs_sibling_cardinality': float(abs_sibling_cardinality),
      'abs_depth': float(abs_depth),
      'avg_depth': float(avg_depth),
      'max_depth': float(max_depth_val),
      'abs_breadth': float(abs_breadth),
      'avg_breadth': float(avg_breadth),
      'max_breadth': float(max_breadth),
      'min_breadth': float(min_breadth),
      'ratio_leaf_fanoutness': float(ratio_leaf_fanoutness),
      'ratio_sibling_fanoutness': float(ratio_sibling_fanoutness),
      'tangledness': float(tangledness),
      'num_multi_parent_classes': float(num_multi_parent),
      'TNOP': float(TNOP),
      'ANOP': float(ANOP),
      'cycle_detected': 1.0 if cycle_detected else 0.0,
  }


# ── Class identification ──────────────────────────────────────────────────
def identify_classes(g: Graph) -> Dict[URIRef, Dict[str, str]]:
  classes: Dict[URIRef, Dict[str, str]] = {}

  XSD = Namespace("http://www.w3.org/2001/XMLSchema#")
  RDF_CLASS = URIRef("http://www.w3.org/1999/02/22-rdf-syntax-ns#Class")

  OWL_EXCLUDES = {
      OWL.Ontology, OWL.Restriction, OWL.DeprecatedClass, OWL.ObjectProperty,
      OWL.TransitiveProperty, OWL.DatatypeProperty, OWL.FunctionalProperty,
      OWL.DeprecatedProperty, OWL.Thing, OWL.Nothing, OWL.AnnotationProperty,
      OWL.SymmetricProperty, OWL.InverseFunctionalProperty,
  }

  ADDITIONAL_EXCLUDES = {
      RDFS.Class, OWL.Class,
      URIRef("http://www.w3.org/1999/02/22-rdf-syntax-ns#Property"),
      RDFS.Datatype, RDFS.Resource, RDFS.Literal,
  }

  for s in g.subjects(RDF.type, OWL.Class):
      if isinstance(s, URIRef) and s not in OWL_EXCLUDES and s not in ADDITIONAL_EXCLUDES:
          classes[s] = {'type': 'explicit_owlClass'}

  for s in g.subjects(RDF.type, RDFS.Class):
      if isinstance(s, URIRef) and s not in OWL_EXCLUDES and s not in ADDITIONAL_EXCLUDES:
          classes.setdefault(s, {'type': 'explicit_rdfsClass'})

  for s in g.subjects(RDF.type, RDF_CLASS):
      if isinstance(s, URIRef) and s not in OWL_EXCLUDES and s not in ADDITIONAL_EXCLUDES:
          classes.setdefault(s, {'type': 'explicit_rdfClass'})

  for _, _, o in g.triples((None, RDF.type, None)):
      if not isinstance(o, URIRef):
          continue

      if o in classes:
          continue

      if o in OWL_EXCLUDES or o in ADDITIONAL_EXCLUDES or str(o).startswith(str(XSD)):
          continue

      classes[o] = {'type': 'inferred_rdftype_object'}

  return classes


def build_valid_class_set(g: Graph) -> Set[URIRef]:
  classes = {c for c in identify_classes(g).keys() if isinstance(c, URIRef)}

  if not INCLUDE_OWL_THING_NOTHING:
      classes.discard(OWL.Thing)
      classes.discard(OWL.Nothing)

  return classes


# ── Basic element counting ───────────────────────────────────────────────
def count_basic_ontology_elements(g: Graph) -> Dict:
  object_properties = {
      s for s in g.subjects(RDF.type, OWL.ObjectProperty)
      if isinstance(s, URIRef)
  }

  datatype_properties = {
      s for s in g.subjects(RDF.type, OWL.DatatypeProperty)
      if isinstance(s, URIRef)
  }

  annotation_properties = {
      s for s in g.subjects(RDF.type, OWL.AnnotationProperty)
      if isinstance(s, URIRef)
  }

  named_individuals = {
      s for s in g.subjects(RDF.type, OWL.NamedIndividual)
      if isinstance(s, URIRef)
  }

  valid_classes = build_valid_class_set(g)

  non_individual_types = valid_classes | {
      OWL.Class, RDFS.Class, OWL.Thing, OWL.Nothing, OWL.Restriction, OWL.DeprecatedClass,
      RDFS.Datatype, RDFS.Resource, RDFS.Literal,
      URIRef("http://www.w3.org/1999/02/22-rdf-syntax-ns#Class"),
      OWL.ObjectProperty, OWL.DatatypeProperty, OWL.AnnotationProperty,
      OWL.TransitiveProperty, OWL.SymmetricProperty, OWL.AsymmetricProperty,
      OWL.ReflexiveProperty, OWL.IrreflexiveProperty, OWL.FunctionalProperty,
      OWL.InverseFunctionalProperty, OWL.DeprecatedProperty,
      RDF.Property, RDFS.ContainerMembershipProperty,
      OWL.Ontology, OWL.AllDisjointClasses, OWL.AllDisjointProperties,
      OWL.AllDifferent, OWL.NegativePropertyAssertion,
      RDF.List, RDF.Seq, RDF.Bag, RDF.Alt,
      URIRef("http://www.w3.org/2002/07/owl#Axiom"),
      URIRef("http://www.w3.org/2002/07/owl#Annotation"),
  }

  inferred_individuals: Set[URIRef] = set()

  for s, _, o in g.triples((None, RDF.type, None)):
      if isinstance(s, URIRef) and isinstance(o, URIRef) and o not in non_individual_types:
          inferred_individuals.add(s)

  functional_datatype_properties = {
      s for s in g.subjects(RDF.type, OWL.FunctionalProperty)
      if isinstance(s, URIRef) and (s, RDF.type, OWL.DatatypeProperty) in g
  }

  inverse_functional_datatype_properties = {
      s for s in g.subjects(RDF.type, OWL.InverseFunctionalProperty)
      if isinstance(s, URIRef) and (s, RDF.type, OWL.DatatypeProperty) in g
  }

  props_with_inverse: Set[URIRef] = set()

  for s, _, o in g.triples((None, OWL.inverseOf, None)):
      if isinstance(s, URIRef):
          props_with_inverse.add(s)
      if isinstance(o, URIRef):
          props_with_inverse.add(o)

  non_empty_classes = {
      o for _, _, o in g.triples((None, RDF.type, None))
      if isinstance(o, URIRef) and o in valid_classes
  }

  individuals = named_individuals | inferred_individuals

  return {
      'num_object_properties': len(object_properties),
      'num_datatype_properties': len(datatype_properties),
      'num_annotation_properties': len(annotation_properties),
      'num_individuals': len(individuals),
      'num_functional_datatype': len(functional_datatype_properties),
      'num_inverse_functional_datatype': len(inverse_functional_datatype_properties),
      'num_props_with_inverse': len(props_with_inverse),
      'num_non_empty_classes': len(non_empty_classes),
      'individuals_set': individuals,
  }


# ── Subclass edges ────────────────────────────────────────────────────────────
def iter_valid_subclass_edges(
  g: Graph,
  valid_classes: Set[URIRef],
) -> List[Tuple[URIRef, URIRef]]:

  edges = []

  for child, parent in g.subject_objects(RDFS.subClassOf):
      if not isinstance(child, URIRef) or child not in valid_classes:
          continue

      if not COUNT_BNODE_SUPERCLASSES and not isinstance(parent, URIRef):
          continue

      if isinstance(parent, URIRef):
          edges.append((child, parent))

  return edges


def inheritance_richness(g: Graph):
  valid_classes = build_valid_class_set(g)
  C = len(valid_classes)

  if C == 0:
      return 0.0, 0, 0, set(), []

  edges = iter_valid_subclass_edges(g, valid_classes)
  H = len(edges)

  return H / C, H, C, valid_classes, edges


def valid_uri_class(x, valid_classes: Set[URIRef]) -> bool:
  return isinstance(x, URIRef) and x in valid_classes


def count_non_taxonomic_relationship_assertions(
  g: Graph,
  valid_classes: Set[URIRef],
) -> int:

  P = 0

  for prop in g.subjects(RDF.type, OWL.ObjectProperty):
      if not isinstance(prop, URIRef):
          continue

      domains = [
          d for d in g.objects(prop, RDFS.domain)
          if valid_uri_class(d, valid_classes)
      ]

      ranges = [
          r for r in g.objects(prop, RDFS.range)
          if valid_uri_class(r, valid_classes)
      ]

      if domains and ranges:
          P += len(domains) * len(ranges)

  if COUNT_RESTRICTION_AXIOMS_AS_RELATIONSHIPS:
      for c, _, b in g.triples((None, RDFS.subClassOf, None)):
          if not valid_uri_class(c, valid_classes) or not isinstance(b, BNode):
              continue

          for constraint in (OWL.someValuesFrom, OWL.allValuesFrom):
              for o in g.objects(b, constraint):
                  if valid_uri_class(o, valid_classes):
                      P += 1

  return P


def class_relation_ratio_assertions(
  g: Graph,
  C: int,
  H_taxonomic: int,
  valid_classes: Set[URIRef],
) -> Dict[str, float]:

  P = count_non_taxonomic_relationship_assertions(g, valid_classes)
  R = H_taxonomic + P

  return {
      'R_total': float(R),
      'H_taxonomic': float(H_taxonomic),
      'P_nontaxonomic': float(P),
      'crr': C / R if R > 0 else 0.0,
  }


# ── Semantic richness ─────────────────────────────────────────────────────────
def iter_literal_values(
  g: Graph,
  s: URIRef,
  props: Iterable[URIRef],
) -> List[str]:

  return [
      str(o)
      for p in props
      for o in g.objects(s, p)
      if isinstance(o, Literal)
  ]


def build_class_text_index(
  g: Graph,
  valid_classes: Set[URIRef],
) -> Dict[URIRef, Dict[str, Set[str]]]:

  idx: Dict[URIRef, Dict[str, Set[str]]] = {}

  for c in valid_classes:
      strict_raw = [uri_local_name(c)] + iter_literal_values(g, c, NAME_PROPS_STRICT)
      strict_norm = {normalize_text(x) for x in strict_raw if normalize_text(x)}
      desc_norm = {
          normalize_text(x)
          for x in iter_literal_values(g, c, DESC_PROPS)
          if normalize_text(x)
      }

      idx[c] = {
          'names_strict': strict_norm,
          'all_extended': strict_norm | desc_norm,
      }

  return idx


def build_taxonomy_neighbors(valid_subclass_edges):
  parents_of: Dict[URIRef, Set[URIRef]] = defaultdict(set)
  children_of: Dict[URIRef, Set[URIRef]] = defaultdict(set)

  for child, parent in valid_subclass_edges:
      parents_of[child].add(parent)
      children_of[parent].add(child)

  return parents_of, children_of


def semantic_richness_for_all_classes(
  g: Graph,
  valid_classes: Set[URIRef],
  valid_subclass_edges,
  class_index,
) -> Dict[str, float]:

  if not valid_classes:
      return {
          'sr': 0.0,
          'avg_Ri': 0.0,
          'avg_Ai': 0.0,
          'avg_Si': 0.0,
      }

  parents_of, children_of = build_taxonomy_neighbors(valid_subclass_edges)
  class_prop_assoc: Dict[URIRef, Set[URIRef]] = defaultdict(set)

  for rdf_type in (OWL.ObjectProperty, OWL.DatatypeProperty):
      for prop in g.subjects(RDF.type, rdf_type):
          if not isinstance(prop, URIRef):
              continue

          for dom in g.objects(prop, RDFS.domain):
              if isinstance(dom, URIRef) and dom in valid_classes:
                  class_prop_assoc[dom].add(prop)

          if rdf_type == OWL.ObjectProperty:
              for rng in g.objects(prop, RDFS.range):
                  if isinstance(rng, URIRef) and rng in valid_classes:
                      class_prop_assoc[rng].add(prop)

  anno_props = set(NAME_PROPS_STRICT) | set(DESC_PROPS)

  total_R = total_A = total_S = 0
  m = len(valid_classes)

  for c in valid_classes:
      supers = parents_of.get(c, set())
      subs = children_of.get(c, set())

      siblings: Set[URIRef] = set()

      for p in supers:
          siblings.update(children_of.get(p, set()))

      siblings.discard(c)

      total_R += len(supers) + len(subs) + len(siblings)
      total_A += len(class_prop_assoc.get(c, set()))
      total_S += sum(1 for prop in anno_props if list(g.objects(c, prop)))

  avg_R = total_R / m
  avg_A = total_A / m
  avg_S = total_S / m

  return {
      'sr': avg_R + avg_A + avg_S,
      'avg_Ri': avg_R,
      'avg_Ai': avg_A,
      'avg_Si': avg_S,
  }


