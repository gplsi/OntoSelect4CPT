#!/usr/bin/env python3
"""
Compute semantic similarity between a task description and ontology embeddings.

How it works
------------
Read TASK_FILE and split its text into overlapping whitespace-delimited word
chunks. Encode each chunk using MODEL_NAME, averaging its final-layer token
representations, then average the chunk embeddings to obtain one task vector.
Compare this vector with each precomputed ontology embedding using cosine
similarity. Assign quartile labels from the 75th, 50th, and 25th percentiles:
quartile "1" contains the highest similarities and quartile "4" the lowest.
Ties at percentile boundaries may produce unequal quartile counts.

ONTOLOGY_EMBEDDINGS_FILE is generated by compute_ontology_embeddings.py and
maps ontology filenames to embedding lists (or null). Null embeddings receive
a similarity of 0.0 and are included in the percentile calculations.

Write filename-keyed similarity and quartile entries to OUTPUT_FILE, along
with a reserved _statistics entry containing summary statistics. This output
can be used as SIMILARITY_JSON by analyze_ontology_metrics.py.

Setup and execution
-------------------
1. Install dependencies:
     python3 -m pip install transformers torch numpy tqdm einops
2. Set TASK_FILE, ONTOLOGY_EMBEDDINGS_FILE, and OUTPUT_FILE below.
 Create the output parent directory before running.
3. Use the same embedding model as compute_ontology_embeddings.py so that the
 task and ontology vectors share the same representation space.
4. Run:
     python3 compute_semantic_similarity.py

Use CUDA when available, otherwise CPU. The model/tokenizer may be downloaded
on first use. Model loading uses trust_remote_code=True.

CONTEXT_WINDOW controls both the word chunk size and the tokenizer token
limit. Word chunks may exceed that token limit and are then truncated during
encoding. This preserves the original chunking and pooling behavior.
"""

import json
import time

from transformers import AutoTokenizer, AutoModel
import torch
import numpy as np
from tqdm import tqdm


# Configuration: fill in all three file paths before running.
TASK_FILE = ""
ONTOLOGY_EMBEDDINGS_FILE = ""
OUTPUT_FILE = ""

MODEL_NAME = "nomic-ai/nomic-embed-text-v1.5"
CONTEXT_WINDOW = 8192
OVERLAP = 2048


def load_task_text(task_file):
  """Read the task description as UTF-8 text."""
  with open(task_file, "r", encoding="utf-8") as f:
      return f.read()


def chunk_text(text, chunk_size, overlap):
  """Split text into overlapping whitespace-delimited word chunks."""
  tokens = text.split()
  chunks = []
  i = 0

  while i < len(tokens):
      chunk = tokens[i:i + chunk_size]
      chunks.append(" ".join(chunk))

      if i + chunk_size >= len(tokens):
          break

      i += chunk_size - overlap

  return chunks


def embed_texts(texts, tokenizer, model, device):
  """Encode chunks and average final-layer token representations."""
  embeddings = []

  for text in tqdm(texts, desc="Embedding chunks"):
      inputs = tokenizer(
          text,
          return_tensors="pt",
          truncation=True,
          max_length=CONTEXT_WINDOW,
          padding=True
      ).to(device)

      with torch.no_grad():
          emb = model(**inputs).last_hidden_state.mean(dim=1).cpu().numpy()

      embeddings.append(emb[0])

  return np.array(embeddings)


def mean_pool(embeddings):
  """Average chunk vectors with equal weights."""
  return np.mean(embeddings, axis=0)


def cosine_similarity(a, b):
  """Return cosine similarity between two vectors."""
  a = a / np.linalg.norm(a)
  b = b / np.linalg.norm(b)
  return float(np.dot(a, b))


def main():
  if not all(path.strip() for path in (TASK_FILE, ONTOLOGY_EMBEDDINGS_FILE, OUTPUT_FILE)):
      raise ValueError(
          "Set TASK_FILE, ONTOLOGY_EMBEDDINGS_FILE, and OUTPUT_FILE before running."
      )

  start_time = time.time()

  device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
  print(f"Using device: {device}")

  tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
  model = AutoModel.from_pretrained(
      MODEL_NAME,
      trust_remote_code=True
  ).to(device)

  model.eval()

  # 1. Compute the task embedding.
  task_text = load_task_text(TASK_FILE)
  task_chunks = chunk_text(task_text, CONTEXT_WINDOW, OVERLAP)

  print(f"Number of task chunks: {len(task_chunks)}")

  task_emb_chunks = embed_texts(task_chunks, tokenizer, model, device)
  task_embedding = mean_pool(task_emb_chunks)

  # 2. Load the precomputed ontology embeddings.
  with open(ONTOLOGY_EMBEDDINGS_FILE, "r", encoding="utf-8") as f:
      ontology_data = json.load(f)

  results = {}
  similarities = []

  # First pass: compute similarities.
  for ontology, emb in tqdm(ontology_data.items(), desc="Comparing ontologies"):
      if emb is None:
          results[ontology] = {"similarity": 0.0}
          similarities.append(0.0)
          continue

      ontology_emb = np.array(emb)
      sim = cosine_similarity(task_embedding, ontology_emb)

      results[ontology] = {"similarity": sim}
      similarities.append(sim)

  # Calculate quartile thresholds.
  similarities = np.array(similarities)

  q1_threshold = np.percentile(similarities, 75)
  q2_threshold = np.percentile(similarities, 50)
  q3_threshold = np.percentile(similarities, 25)

  # Second pass: assign quartiles, with quartile 1 ranked highest.
  for ontology in results.keys():
      sim = results[ontology]["similarity"]

      if sim >= q1_threshold:
          quartile = "1"
      elif sim >= q2_threshold:
          quartile = "2"
      elif sim >= q3_threshold:
          quartile = "3"
      else:
          quartile = "4"

      results[ontology]["quartile"] = quartile

  # Summarize the quartile distribution.
  quartile_stats = {
      "1": {"threshold": f">= {q1_threshold:.4f}", "count": 0},
      "2": {"threshold": f"{q2_threshold:.4f} - {q1_threshold:.4f}", "count": 0},
      "3": {"threshold": f"{q3_threshold:.4f} - {q2_threshold:.4f}", "count": 0},
      "4": {"threshold": f"< {q3_threshold:.4f}", "count": 0}
  }

  for ontology_result in results.values():
      quartile_stats[ontology_result["quartile"]]["count"] += 1

  results["_statistics"] = {
      "total_ontologies": len(results),
      "quartile_distribution": quartile_stats,
      "similarity_range": {
          "max": float(np.max(similarities)),
          "min": float(np.min(similarities)),
          "mean": float(np.mean(similarities)),
          "std": float(np.std(similarities))
      }
  }

  with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
      json.dump(results, f, indent=2, ensure_ascii=False)

  end_time = time.time()
  elapsed_minutes = (end_time - start_time) / 60

  print(f"\nSimilarity results saved to {OUTPUT_FILE}")

  print("\nQuartile Distribution:")
  stats = results["_statistics"]

  for q in ["1", "2", "3", "4"]:
      count = stats["quartile_distribution"][q]["count"]
      threshold = stats["quartile_distribution"][q]["threshold"]
      print(f"  {q}: {count} ontologies (similarity {threshold})")

  print("\nSimilarity Statistics:")
  print(f"  Range: {stats['similarity_range']['min']:.4f} - {stats['similarity_range']['max']:.4f}")
  print(f"  Mean: {stats['similarity_range']['mean']:.4f} +/- {stats['similarity_range']['std']:.4f}")

  print(f"\nTotal execution time: {elapsed_minutes:.2f} minutes")


if __name__ == "__main__":
  main()
