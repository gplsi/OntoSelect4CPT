# ── Utilities ────────────────────────────────────────────────────────────────
def count_llama_tokens(tokenizer, filepath) -> int:
  # Same defaults as compute_tokens.py; these are not semantic tokens.
  text = Path(filepath).read_text(encoding="utf-8", errors="replace")
  return len(tokenizer.encode(text, add_special_tokens=False, truncation=False))


def get_file_size_mb(filepath):
  try:
      return round(os.path.getsize(filepath) / (1024 * 1024), 2)
  except Exception as e:
      logger.warning(f"Error obtaining file size for {filepath}: {e}")
      return 0


def get_file_char_count(filepath):
  try:
      with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
          return len(f.read())
  except Exception as e:
      logger.warning(f"Error counting characters in {filepath}: {e}")
      return 0


def read_file_text(filepath: str) -> str:
  try:
      with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
          return f.read()
  except Exception as e:
      logger.warning(f"Could not read text from {filepath}: {e}")
      return ""


def load_similarity_map(json_path: str) -> Dict[str, float]:
  """Load filename-to-similarity scores from the JSON generated by
  compute_semantic_similarity.py. Entries must contain a similarity field.
  Return {"ontology.ttl": 0.55}; return an empty mapping if loading fails."""
  try:
      with open(json_path, "r", encoding="utf-8") as f:
          data = json.load(f)

      similarity_map = {
          filename: float(info["similarity"])
          for filename, info in data.items()
          if isinstance(info, dict) and "similarity" in info
      }

      logger.info(f"Similarity scores loaded from JSON: {len(similarity_map)}")
      return similarity_map

  except Exception as e:
      logger.warning(f"Could not load similarity JSON {json_path}: {e}")
      return {}


def camel_to_spaces(s: str) -> str:
  return re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', s)


def normalize_text(s: str) -> str:
  if s is None:
      return s
  s = str(s).strip()
  if NORMALIZE_CAMEL_CASE:
      s = camel_to_spaces(s)
  if SPLIT_UNDERSCORE_DASH:
      s = s.replace('_', ' ').replace('-', ' ')
  s = s.lower()
  s = wordsep_re.sub(' ', s)
  return re.sub(r'\s+', ' ', s).strip()


def uri_local_name(u: URIRef) -> str:
  txt = str(u)
  if '#' in txt:
      return txt.rsplit('#', 1)[-1]
  return txt.rstrip('/').rsplit('/', 1)[-1]


# ── RDF/OWL textual and semantic metrics ─────────────────────────────────────
def semantic_tokenize(text: str) -> List[str]:
  tokens = []

  for match in re.findall(r'\b(\w+):(\w+)\b', text):
      tokens.extend(match)

  text_cleaned = re.sub(r'\b\w+:\w+\b', '', text)
  tokens.extend(re.findall(r'\b\w+\b', text_cleaned))

  return tokens


def vocab_specific_density(text: str, vocab: Set[str]) -> float:
  raw_lines = text.splitlines()
  cleaned_lines = [line.strip() for line in raw_lines if line.strip()]

  if not cleaned_lines:
      return 0.0

  vocab_count = 0

  for line in cleaned_lines:
      literals = {}

      def replacer(m):
          key = f"__LIT{len(literals)}__"
          literals[key] = m.group(0)
          return key

      masked = re.sub(r'"""(.*?)"""', replacer, line, flags=re.DOTALL)
      masked = re.sub(r'"(.*?)"', replacer, masked)

      tokens = (
          re.findall(r'\b\w+:\w+\b', masked)
          +
          re.findall(r'\b\w+\b', re.sub(r'\b\w+:\w+\b', '', masked))
      )

      vocab_count += sum(1 for tok in tokens if tok in vocab)

  return vocab_count / len(cleaned_lines)


def vocab_specific_diversity(text: str, vocab: Set[str]) -> float:
  tokens = re.findall(r'\b\w+:\w+\b', text)
  used_vocab_terms = {tok for tok in tokens if tok in vocab}
  return len(used_vocab_terms) / len(vocab) if vocab else 0.0


def logical_block_uniqueness_ratio(text: str) -> float:
  lines = [
      line.strip()
      for line in text.splitlines()
      if line.strip()
      and not line.strip().startswith("#")
      and not line.strip().startswith("@")
  ]

  combined_text = " ".join(lines)

  literals = {}

  def replacer(m):
      key = f"__LIT{len(literals)}__"
      literals[key] = m.group(0)
      return key

  masked = re.sub(r'"""(.*?)"""', replacer, combined_text, flags=re.DOTALL)
  masked = re.sub(r'"(.*?)"', replacer, masked)

  phrases = [p.strip() for p in re.split(r'\s*\.\s+', masked) if p.strip()]

  return len(set(phrases)) / len(phrases) if phrases else 0.0


def line_uniqueness_ratio(text: str) -> float:
  lines = [line.strip() for line in text.splitlines() if line.strip()]
  return len(set(lines)) / len(lines) if lines else 0.0


def brunet_index(text: str) -> float:
  tokens = semantic_tokenize(text)
  N = len(tokens)
  V = len(set(tokens))

  return N ** (V ** -0.165) if V else 0.0


def compute_annotation_to_structure_ratio(g: Graph, text: str) -> float:
  total_literal_chars = 0

  for _, _, o in g:
      if isinstance(o, Literal):
          total_literal_chars += len(str(o))

  total_chars = len(text)

  if total_chars == 0:
      return 0.0

  return total_literal_chars / total_chars


def compute_literal_coverage_ratio(
  g: Graph,
  valid_classes: Set[URIRef],
) -> float:

  if not valid_classes:
      return 0.0

  classes_with_literals: Set[URIRef] = set()

  for s, _, o in g:
      if isinstance(s, URIRef) and s in valid_classes and isinstance(o, Literal):
          if str(o).strip():
              classes_with_literals.add(s)

  return len(classes_with_literals) / len(valid_classes)


def compute_textual_semantic_metrics(
  g: Graph,
  text: str,
  valid_classes: Set[URIRef],
) -> Dict[str, float]:
  return {
      "vocab_specific_density": float(vocab_specific_density(text, SEMANTIC_VOCAB)),
      "vocab_specific_diversity": float(vocab_specific_diversity(text, SEMANTIC_VOCAB)),
      "logical_block_uniqueness_ratio": float(logical_block_uniqueness_ratio(text)),
      "line_uniqueness_ratio": float(line_uniqueness_ratio(text)),
      "brunet_index": float(brunet_index(text)),
      "annotation_to_structure_ratio": float(compute_annotation_to_structure_ratio(g, text)),
      "literal_coverage_ratio": float(compute_literal_coverage_ratio(g, valid_classes)),
  }


