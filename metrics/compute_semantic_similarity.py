"""Analyze Turtle ontologies and export structural, textual, and semantic metrics.

How it works
------------
Recursively discover TTL files under BASEPATH, respecting EXCLUDE_PATHS.
Parse each ontology with RDFLib and compute axiom, schema, knowledge base,
graph, lexical diversity, uniqueness, and annotation metrics. Count file tokens
with LLAMA_TOKENIZER_MODEL and attach semantic similarity scores by filename.
Compute QS as the sum of min-max normalized SC, NTR, and PD across all analyzed
files; recompute it whenever the workbook is saved. Export per-ontology details,
domain summaries, and overall statistics to an Excel workbook updated after
each processed file.

The similarity_json input configured through SIMILARITY_JSON is generated by
compute_semantic_similarity.py. Run that script first for the corpus to analyze.
Expected JSON format:
  {"ontology.ttl": {"similarity": 0.55, "quartile": "1"}}
Only the similarity field is read; missing scores are recorded as empty values.

Setup and execution
-------------------
1. Install dependencies:
     python3 -m pip install rdflib pandas openpyxl transformers
2. Set BASEPATH, OUTPUT_FILE (an .xlsx file), and SIMILARITY_JSON.
 Optionally configure EXCLUDE_PATHS and the metric settings below.
3. Ensure access to LLAMA_TOKENIZER_MODEL on Hugging Face; set HF_TOKEN in the
 environment if authentication is required. The tokenizer may be downloaded
 on first use.
4. Run:
     python3 analyze_ontology_metrics.py
"""

