"""Compute a quality index from suitable ontology metrics.

Inputs
------
1. A dataset workbook containing one row per ontology.
2. A correlation workbook containing the Todas and Aptas worksheets,
   generated by correlate_metrics_with_f1.py.

For each suitable metric j:
    x_norm = (x - min(x)) / (max(x) - min(x))
    x_oriented = x_norm                 for a positive direction
    x_oriented = 1 - x_norm             for a negative direction
    contribution = association_score * x_oriented

The final index is a weighted mean:
    association_correlation_score = sum(contribution) / sum(association_score)

Constant metrics receive a neutral normalized value of 0.5. All metric values
must be numeric and finite; association weights must be finite and positive.
Only columns listed in Todas and absent from Aptas are removed. Other dataset
columns are retained. Append normalized, oriented, and weighted values for
each suitable metric, followed by association_correlation_score.

Requirements:
    Python 3.9 or later and openpyxl.
    python3 -m pip install openpyxl

Execution:
    python3 score_corpus_files.py \
        --dataset DATASET_XLSX \
        --correlations CORRELATIONS_XLSX \
        --output OUTPUT_XLSX

The output must differ from both input files. Override worksheet names using
--dataset-sheet, --all-sheet, and --apt-sheet. Existing column and worksheet
identifiers are retained. Direction values accept English (positive/negative)
and legacy Spanish (positiva/negativa) correlation workbooks.
"""

from __future__ import annotations

import argparse
import math
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from openpyxl import load_workbook


@dataclass(frozen=True)
class MetricConfig:
    name: str
    direction: str
    weight: float


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Filter metrics, apply min-max normalization, orient values, and compute a weighted index."
    )
    parser.add_argument("--dataset", type=Path, required=True, help="Dataset workbook containing all ontologies.")
    parser.add_argument("--correlations", type=Path, required=True, help="Correlation workbook containing the Todas and Aptas worksheets.")
    parser.add_argument("--output", type=Path, required=True, help="Path of the output Excel workbook.")
    parser.add_argument(
        "--dataset-sheet",
        default="DetalleOntologías",
        help="Dataset worksheet to process (default: DetalleOntologías).",
    )
    parser.add_argument("--all-sheet", default="Todas", help="Worksheet listing all analyzed metrics.")
    parser.add_argument("--apt-sheet", default="Aptas", help="Worksheet containing the suitable metrics.")
    return parser.parse_args()


def normalize_header(value: Any) -> str:
    return str(value).strip() if value is not None else ""


def header_positions(worksheet) -> dict[str, int]:
    positions: dict[str, int] = {}
    duplicates: list[str] = []
    for cell in worksheet[1]:
        name = normalize_header(cell.value)
        if not name:
            continue
        if name in positions:
            duplicates.append(name)
        positions[name] = cell.column
    if duplicates:
        raise ValueError(f"Duplicate headers: {', '.join(sorted(set(duplicates)))}")
    return positions


def read_metric_names(worksheet) -> list[str]:
    headers = header_positions(worksheet)
    if "Métrica" not in headers:
        raise ValueError(f"Worksheet '{worksheet.title}' does not contain the 'Métrica' column.")
    column = headers["Métrica"]
    names: list[str] = []
    for row in range(2, worksheet.max_row + 1):
        name = normalize_header(worksheet.cell(row, column).value)
        if name:
            names.append(name)
    if len(names) != len(set(names)):
        raise ValueError(f"Duplicate metrics in worksheet '{worksheet.title}'.")
    return names


def read_apt_metrics(worksheet) -> list[MetricConfig]:
    headers = header_positions(worksheet)
    required = {"Métrica", "Dirección", "Association_score"}
    missing_headers = sorted(required - headers.keys())
    if missing_headers:
        raise ValueError(
            f"Worksheet '{worksheet.title}' is missing: {', '.join(missing_headers)}"
        )

    configs: list[MetricConfig] = []
    for row in range(2, worksheet.max_row + 1):
        name = normalize_header(worksheet.cell(row, headers["Métrica"]).value)
        if not name:
            continue

        direction = normalize_header(worksheet.cell(row, headers["Dirección"]).value).lower()
        # Accept current English output and legacy Spanish direction labels.
        direction = {"positiva": "positive", "negativa": "negative"}.get(direction, direction)
        if direction not in {"positive", "negative"}:
            raise ValueError(f"Invalid direction for '{name}': {direction!r}")

        raw_weight = worksheet.cell(row, headers["Association_score"]).value
        try:
            weight = float(raw_weight)
        except (TypeError, ValueError) as error:
            raise ValueError(f"Non-numeric Association_score for '{name}': {raw_weight!r}") from error
        if not math.isfinite(weight) or weight <= 0:
            raise ValueError(f"Association_score must be finite and positive for '{name}': {weight}")

        configs.append(MetricConfig(name=name, direction=direction, weight=weight))

    if not configs:
        raise ValueError(f"Worksheet '{worksheet.title}' contains no suitable metrics.")
    if len({config.name for config in configs}) != len(configs):
        raise ValueError(f"Duplicate metrics in worksheet '{worksheet.title}'.")
    return configs


def as_finite_float(value: Any, metric: str, excel_row: int) -> float:
    if isinstance(value, bool):
        raise ValueError(f"Boolean value in '{metric}', row {excel_row}.")
    try:
        number = float(value)
    except (TypeError, ValueError) as error:
        raise ValueError(f"Non-numeric value in '{metric}', row {excel_row}: {value!r}") from error
    if not math.isfinite(number):
        raise ValueError(f"Non-finite value in '{metric}', row {excel_row}: {value!r}")
    return number


def main() -> int:
    args = parse_args()
    dataset_path = args.dataset.resolve()
    correlations_path = args.correlations.resolve()
    output_path = args.output.resolve()

    if not dataset_path.is_file():
        print(f"ERROR: dataset file not found: {dataset_path}", file=sys.stderr)
        return 1
    if not correlations_path.is_file():
        print(f"ERROR: correlation workbook not found: {correlations_path}", file=sys.stderr)
        return 1
    if output_path == dataset_path or output_path == correlations_path:
        print("ERROR: the output must differ from both input files; input files cannot be overwritten.", file=sys.stderr)
        return 1

    try:
        correlation_book = load_workbook(correlations_path, read_only=True, data_only=True)
        for sheet_name in (args.all_sheet, args.apt_sheet):
            if sheet_name not in correlation_book.sheetnames:
                raise ValueError(f"Worksheet '{sheet_name}' not found in the correlation workbook.")
        all_metrics = set(read_metric_names(correlation_book[args.all_sheet]))
        apt_metrics = read_apt_metrics(correlation_book[args.apt_sheet])
        correlation_book.close()

        apt_names = {config.name for config in apt_metrics}
        if not apt_names.issubset(all_metrics):
            extras = sorted(apt_names - all_metrics)
            raise ValueError(f"These suitable metrics are not listed in 'Todas': {', '.join(extras)}")

        workbook = load_workbook(dataset_path)
        if args.dataset_sheet not in workbook.sheetnames:
            workbook.close()
            raise ValueError(f"Worksheet '{args.dataset_sheet}' not found in the dataset.")
        worksheet = workbook[args.dataset_sheet]
        headers = header_positions(worksheet)

        missing_apt = [config.name for config in apt_metrics if config.name not in headers]
        if missing_apt:
            workbook.close()
            raise ValueError(f"Suitable metrics missing from the dataset: {', '.join(missing_apt)}")

        # Only remove columns identified as metrics in the 'Todas' worksheet.
        # Retain descriptive, identifier, and token count columns.
        non_apt_columns = sorted(
            (headers[name] for name in all_metrics - apt_names if name in headers),
            reverse=True,
        )
        for column_index in non_apt_columns:
            worksheet.delete_cols(column_index, 1)

        headers = header_positions(worksheet)
        if worksheet.max_row < 2:
            workbook.close()
            raise ValueError("The dataset contains no data rows.")

        values_by_metric: dict[str, list[float]] = {}
        min_max: dict[str, tuple[float, float]] = {}
        for config in apt_metrics:
            column = headers[config.name]
            values = [
                as_finite_float(worksheet.cell(row, column).value, config.name, row)
                for row in range(2, worksheet.max_row + 1)
            ]
            values_by_metric[config.name] = values
            min_max[config.name] = (min(values), max(values))

        # Use a neutral value of 0.5 for constant metrics. Using 0 would
        # artificially transform a constant negative-direction metric into 1.
        derived_columns: list[tuple[str, list[float]]] = []
        oriented_by_metric: dict[str, list[float]] = {}
        for config in apt_metrics:
            minimum, maximum = min_max[config.name]
            if maximum == minimum:
                normalized = [0.5] * len(values_by_metric[config.name])
            else:
                denominator = maximum - minimum
                normalized = [
                    (value - minimum) / denominator
                    for value in values_by_metric[config.name]
                ]
            oriented = (
                normalized
                if config.direction == "positive"
                else [1.0 - value for value in normalized]
            )
            weighted = [config.weight * value for value in oriented]
            oriented_by_metric[config.name] = oriented
            derived_columns.extend(
                [
                    (f"{config.name}__minmax", normalized),
                    (f"{config.name}__oriented", oriented),
                    (f"{config.name}__weighted", weighted),
                ]
            )

        total_weight = sum(config.weight for config in apt_metrics)
        association_scores = [
            sum(
                config.weight * oriented_by_metric[config.name][index]
                for config in apt_metrics
            )
            / total_weight
            for index in range(worksheet.max_row - 1)
        ]
        derived_columns.append(("association_correlation_score", association_scores))

        first_new_column = worksheet.max_column + 1
        for offset, (header, values) in enumerate(derived_columns):
            column = first_new_column + offset
            worksheet.cell(1, column, header)
            for row_offset, value in enumerate(values, start=2):
                cell = worksheet.cell(row_offset, column, value)
                cell.number_format = "0.000000"

        output_path.parent.mkdir(parents=True, exist_ok=True)
        temporary_path = output_path.with_name(f".{output_path.stem}.tmp{output_path.suffix}")
        try:
            workbook.save(temporary_path)
            workbook.close()
            os.replace(temporary_path, output_path)
        finally:
            if temporary_path.exists():
                temporary_path.unlink()

        print(f"Metrics analyzed in 'Todas': {len(all_metrics)}")
        print(f"Suitable metrics used: {len(apt_metrics)}")
        print(f"Unsuitable metrics removed from the dataset: {len(non_apt_columns)}")
        print(f"Rows scored: {len(association_scores)}")
        print(f"Sum of weights: {total_weight:.10f}")
        print(f"Index range: [{min(association_scores):.6f}, {max(association_scores):.6f}]")
        print(f"Output workbook: {output_path}")
        return 0

    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
